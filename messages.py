LEVELS = {
    1: "المستوى الأول 🌱",
    2: "المستوى الثاني 🌿",
    3: "المستوى الثالث 🌳",
    4: "المستوى الرابع 👑",
}

def get_level(referrals: int, thresholds: dict = None) -> tuple[int, str]:
    if thresholds is None:
        thresholds = {1: 0, 2: 10, 3: 50, 4: 200}
    lvl = 1
    for k in sorted(thresholds.keys(), reverse=True):
        if referrals >= thresholds[k]:
            lvl = k
            break
    return lvl, LEVELS.get(lvl, LEVELS[1])
